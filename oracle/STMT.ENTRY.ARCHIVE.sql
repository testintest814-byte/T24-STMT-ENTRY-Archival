-- =============================================================
-- Oracle dev/archive script for STMT.ENTRY -> STMT.ENTRY$ARC
-- Rule: BOOKING.DATE < 20260101
-- Purpose: archive old rows to an archive table, optionally using parallel execution
-- =============================================================

-- 1) Optional archive table creation
CREATE TABLE STMT.ENTRY$ARC (
    ARCHIVE_ID         NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ENTRY_ID           VARCHAR2(60),
    BOOKING_DATE       DATE,
    VALUE_DATE         DATE,
    AMOUNT             NUMBER(18,2),
    CURRENCY           VARCHAR2(10),
    NARRATIVE          VARCHAR2(500),
    ARCHIVED_DATE      DATE DEFAULT SYSDATE,
    ARCHIVED_BY        VARCHAR2(50) DEFAULT USER,
    ARCHIVE_BATCH_ID   VARCHAR2(50),
    STATUS             VARCHAR2(10) DEFAULT 'ARCHIVED'
);

-- 2) Optional index for archive select/reporting
CREATE INDEX IDX_STMT_ENTRY_ARC_BOOKDATE
    ON STMT.ENTRY$ARC(BOOKING_DATE);

-- =============================================================
-- Basic Oracle-native parallel archive
-- This is usually the simplest and most practical approach in a dev environment.
-- Oracle executes the insert in parallel using the PARALLEL hint.
-- =============================================================

INSERT /*+ PARALLEL(s, 4) APPEND */
INTO STMT.ENTRY$ARC (
    ENTRY_ID,
    BOOKING_DATE,
    VALUE_DATE,
    AMOUNT,
    CURRENCY,
    NARRATIVE,
    ARCHIVED_DATE,
    ARCHIVED_BY,
    ARCHIVE_BATCH_ID,
    STATUS
)
SELECT
    s.ENTRY_ID,
    s.BOOKING_DATE,
    s.VALUE_DATE,
    s.AMOUNT,
    s.CURRENCY,
    s.NARRATIVE,
    SYSDATE,
    USER,
    'DEV-BATCH-20260101',
    'ARCHIVED'
FROM STMT.ENTRY s
WHERE s.BOOKING_DATE < TO_DATE('20260101', 'YYYYMMDD')
  AND NVL(s.ARCHIVED_FLAG, 'N') <> 'Y';

-- Update source rows to mark as archived after successful copy
UPDATE STMT.ENTRY s
SET s.ARCHIVED_FLAG = 'Y',
    s.ARCHIVED_DATE = SYSDATE,
    s.ARCHIVE_BATCH_ID = 'DEV-BATCH-20260101'
WHERE s.BOOKING_DATE < TO_DATE('20260101', 'YYYYMMDD')
  AND NVL(s.ARCHIVED_FLAG, 'N') <> 'Y';

COMMIT;

-- =============================================================
-- Optional: more explicit multi-worker version using DBMS_PARALLEL_EXECUTE
-- Use this if you want worker-based chunk processing instead of a single parallel insert.
-- =============================================================

CREATE OR REPLACE PACKAGE stmt_entry_archive_pkg AS
    PROCEDURE archive_dev(
        p_cutoff_date      DATE DEFAULT TO_DATE('20260101', 'YYYYMMDD'),
        p_batch_size       NUMBER DEFAULT 5000,
        p_parallel_workers NUMBER DEFAULT 4
    );

    PROCEDURE process_chunk(
        p_start_rowid IN ROWID,
        p_end_rowid   IN ROWID,
        p_cutoff_date IN DATE
    );
END stmt_entry_archive_pkg;
/

CREATE OR REPLACE PACKAGE BODY stmt_entry_archive_pkg AS

    PROCEDURE process_chunk(
        p_start_rowid IN ROWID,
        p_end_rowid   IN ROWID,
        p_cutoff_date IN DATE
    ) IS
    BEGIN
        FOR rec IN (
            SELECT s.*
            FROM STMT.ENTRY s
            WHERE s.rowid BETWEEN p_start_rowid AND p_end_rowid
              AND s.BOOKING_DATE < p_cutoff_date
              AND NVL(s.ARCHIVED_FLAG, 'N') <> 'Y'
        ) LOOP
            INSERT INTO STMT.ENTRY$ARC (
                ENTRY_ID,
                BOOKING_DATE,
                VALUE_DATE,
                AMOUNT,
                CURRENCY,
                NARRATIVE,
                ARCHIVED_DATE,
                ARCHIVED_BY,
                ARCHIVE_BATCH_ID,
                STATUS
            ) VALUES (
                rec.ENTRY_ID,
                rec.BOOKING_DATE,
                rec.VALUE_DATE,
                rec.AMOUNT,
                rec.CURRENCY,
                rec.NARRATIVE,
                SYSDATE,
                USER,
                'DEV-WORKER',
                'ARCHIVED'
            );

            UPDATE STMT.ENTRY s
            SET s.ARCHIVED_FLAG = 'Y',
                s.ARCHIVED_DATE = SYSDATE,
                s.ARCHIVE_BATCH_ID = 'DEV-WORKER'
            WHERE s.rowid = rec.rowid;

            COMMIT;
        END LOOP;
    EXCEPTION
        WHEN OTHERS THEN
            ROLLBACK;
            RAISE;
    END process_chunk;

    PROCEDURE archive_dev(
        p_cutoff_date      DATE DEFAULT TO_DATE('20260101', 'YYYYMMDD'),
        p_batch_size       NUMBER DEFAULT 5000,
        p_parallel_workers NUMBER DEFAULT 4
    ) IS
        l_task_name VARCHAR2(128) := 'STMT_ENTRY_ARCHIVE_TASK';
    BEGIN
        BEGIN
            DBMS_PARALLEL_EXECUTE.DROP_TASK(l_task_name);
        EXCEPTION
            WHEN OTHERS THEN
                NULL;
        END;

        DBMS_PARALLEL_EXECUTE.CREATE_TASK(task_name => l_task_name);
        DBMS_PARALLEL_EXECUTE.CREATE_CHUNKS_BY_ROWID(
            task_name  => l_task_name,
            by_row     => TRUE,
            chunk_size => p_batch_size,
            table_owner => USER,
            table_name  => 'STMT.ENTRY'
        );

        DBMS_PARALLEL_EXECUTE.RUN_TASK(
            task_name => l_task_name,
            sql_stmt => q'[
                BEGIN
                    stmt_entry_archive_pkg.process_chunk(
                        p_start_rowid => :start_rowid,
                        p_end_rowid   => :end_rowid,
                        p_cutoff_date => TO_DATE('20260101', 'YYYYMMDD')
                    );
                END;
            ]',
            language_flag => DBMS_SQL.NATIVE
        );

        DBMS_PARALLEL_EXECUTE.DROP_TASK(l_task_name);
    END archive_dev;
END stmt_entry_archive_pkg;
/

-- Example execution in dev environment:
BEGIN
    stmt_entry_archive_pkg.archive_dev(
        p_cutoff_date => TO_DATE('20260101', 'YYYYMMDD'),
        p_batch_size => 5000,
        p_parallel_workers => 4
    );
END;
